#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { load } = require("js-yaml");

const root = path.resolve(__dirname, "../..");
const contract = load(fs.readFileSync(path.join(root, "infrastructure/contract/home-lab.yml"), "utf8"));
const cutover = contract.debian.cutover.production_cutover;
const lockPath = path.join(root, cutover.image_lock);
const lockBody = fs.readFileSync(lockPath);
const lock = JSON.parse(lockBody);
const encryptedKeyPath = path.join(root, cutover.tailscale_key_artifact);
const encryptedKeyBody = fs.readFileSync(encryptedKeyPath);
const keyMetadata = JSON.parse(fs.readFileSync(path.join(root, "infrastructure/debian/production-tailscale-authkey.json"), "utf8"));
const keyGenerator = fs.readFileSync(path.join(root, "scripts/controller/create-debian-production-tailscale-key.py"), "utf8");
const archPrepare = fs.readFileSync(path.join(root, "infrastructure/debian/prepare-production-cutover-from-arch.sh"), "utf8");
const production = fs.readFileSync(path.join(root, "infrastructure/debian/run-production-cutover.sh"), "utf8");
const coordinator = fs.readFileSync(path.join(root, "scripts/qualify-debian-inert"), "utf8");
const runner = fs.readFileSync(path.join(root, "scripts/run-debian-production-cutover"), "utf8");
const finalizer = fs.readFileSync(path.join(root, "scripts/finalize-debian-production-cutover"), "utf8");
const revoker = fs.readFileSync(path.join(root, "scripts/controller/revoke-debian-production-tailscale-device.py"), "utf8");
const credentialConfigurator = fs.readFileSync(path.join(root, "scripts/configure-debian-production-tailscale-credentials"), "utf8");

assert.equal(contract.debian.cutover.stage, "production-canary");
assert.equal(cutover.phase, "key-staged");
assert.equal(cutover.scope, "full-compose-and-tailscale");
assert.equal(cutover.compose_artifact_sha256, "d23478a665cfc668efc8bf1296783f05b75a8c84080758c33eb264f45f1e3d5c");
assert.equal(cutover.model_inventory_sha256, "f36ba480734143d51affdc789b2ef782bee063dfb96a248d5048568a82f5a16e");
assert.equal(crypto.createHash("sha256").update(lockBody).digest("hex"), cutover.image_lock_sha256);
assert.equal(lock.schema, 1);
assert.equal(lock.project, "docker-compose");
assert.equal(lock.images.length, cutover.image_service_count);
assert.equal(new Set(lock.images.map((image) => image.service)).size, 41);
assert.equal(new Set(lock.images.map((image) => image.image_id)).size, cutover.unique_image_count);
assert.ok(lock.images.every((image) => /^sha256:[0-9a-f]{64}$/.test(image.image_id)));
assert.ok(lock.images.every((image) => image.repo_digests.length > 0));
assert.equal(cutover.pulls, "disabled");
assert.equal(cutover.tailscale_enrollment, "one-use-preauthorized-key");
assert.equal(cutover.tailscale_version, "1.98.4");
assert.equal(cutover.tailscale_archive_sha256, "e6c08a8ee7e63e69aaf1b62ecd12672b3883fbcd2a176bf6cfa42a15fdce0b6b");
assert.equal(cutover.tailscale_tag, "tag:docker-host");
assert.equal(cutover.tailscale_hostname, "docker-host-debian");
assert.equal(cutover.tailscale_key_delivery, "age-encrypted-debian-recipient");
assert.equal(cutover.tailscale_key_artifact, "infrastructure/debian/production-tailscale-authkey.age");
assert.match(encryptedKeyBody.toString("utf8"), /^age-encryption\.org\/v1\n/);
assert.equal(crypto.createHash("sha256").update(encryptedKeyBody).digest("hex"), keyMetadata.encryptedSha256);
assert.equal(keyMetadata.keyType, "auth");
assert.equal(keyMetadata.expirySeconds, cutover.tailscale_key_expiry_seconds);
assert.deepEqual(keyMetadata.tags, [cutover.tailscale_tag]);
assert.equal(keyMetadata.reusable, false);
assert.equal(keyMetadata.ephemeral, false);
assert.equal(keyMetadata.preauthorized, true);
assert.equal(keyMetadata.plaintextRetained, false);
assert.equal(cutover.production_boot, "pending-physical-reboot-verification");
assert.deepEqual(cutover.rollback_boot_order, ["scsi0", "net0"]);
assert.equal(cutover.rollback_requires_physical_reboot, true);
assert.match(keyGenerator, /reusable": False/);
assert.match(keyGenerator, /ephemeral": False/);
assert.match(keyGenerator, /preauthorized": True/);
assert.match(keyGenerator, /"tags": \[TAG\]/);
assert.match(keyGenerator, /age", "--encrypt", "--recipient", RECIPIENT/);
assert.match(keyGenerator, /"plaintextRetained": False/);
assert.doesNotMatch(keyGenerator, /print\(auth_key|write_text\(auth_key/);
assert.match(keyGenerator, /tailscale-cutover-credentials\.json/);
assert.match(revoker, /tailscale-cutover-credentials\.json/);
assert.match(credentialConfigurator, /read -r -s -p 'Tailscale cutover OAuth client secret/);
assert.match(credentialConfigurator, /chmod 0600 "\$pending"/);
assert.match(archPrepare, /docker image save --output/);
assert.match(archPrepare, /production image lock/);
assert.match(archPrepare, /tailscale_1\.98\.4_amd64\.tgz/);
assert.match(archPrepare, /backupValidation:"existing-local-replicas-sidecar-and-sample"/);
assert.doesNotMatch(archPrepare, /docker compose.*pull|docker exec daily-local-backup/);
assert.match(production, /docker load --input/);
assert.match(production, /compose-image-lock\.py" activate/);
assert.match(production, /--bind-root-override \/srv\/docker-compose\/current/);
assert.match(production, /production Compose model differs[\s\S]*ln -s "\$ARTIFACT_ROOT" "\$DEPLOY_ROOT"/);
assert.match(production, /up --detach --pull never --remove-orphans/);
assert.ok(production.includes("readonly IMAGE_OVERRIDE=/var/lib/home-lab/production-image-override.json"));
assert.ok(production.includes("reduce .images[] as $image"));
assert.ok(production.includes("--file $IMAGE_OVERRIDE up --detach --pull never --remove-orphans"));
assert.ok(production.includes("[.images[] | {service,image_id}] == [$expected[0].images[] | {service,image_id}]"));
assert.ok(production.includes("docker create --name home-lab-image-id-probe \"$probe_image\""));
assert.ok(production.includes("config --images | sort -u"));
assert.ok(production.includes("cleanup_safe=false"));
assert.ok(production.includes("fail-closed guard and activation journal were retained"));
assert.ok(production.indexOf('for service in tailscaled.service home-lab-compose.service docker.service docker.socket containerd.service') < production.indexOf('rm -f -- "$PRODUCTION_ENV" "$ACTIVATION_MARKER"'));
assert.match(production, /containerCount:41/);
assert.match(production, /stateBindCount:115/);
assert.ok(archPrepare.includes('select(.Type == "bind" and (.Source | startswith("/srv/home-lab-state/")))'));
assert.ok(production.includes('select(.Type == "bind" and (.Source | startswith("/srv/home-lab-state/")))'));
assert.ok(coordinator.includes('select(.Type == "bind" and (.Source | startswith("/srv/home-lab-state/")))'));
assert.match(production, /tailscale up --reset --auth-key/);
assert.match(production, /--accept-dns=false/);
assert.match(production, /home-lab-compose\.service/);
assert.match(production, /persist_tailscale_node_id \|\| true/);
assert.match(coordinator, /deploy_stash=\/srv\/docker-compose\/\.current\.finalize/);
assert.match(coordinator, /production_mode == true/);
assert.match(coordinator, /finalize_production_mode == true/);
assert.match(coordinator, /stage=verify-qualified-debian-package-baseline[\s\S]*findmnt -rn --mountpoint/);
assert.doesNotMatch(coordinator, /! findmnt -rn --target/);
assert.ok(coordinator.includes("production_prepare_sha=45c2b585df41ff956db70f02fb6bd28d2f9c42eb23dd2437115195fc4db1d76b"));
assert.ok(coordinator.includes("production_sha=fa5157ea60e32521d6bad4f1933459357cc64372fb3771c1259ba4dae79c8169"));
assert.match(coordinator, /setsid \/bin\/bash \/run\/home-lab-arch-production-prepare\.runner/);
assert.match(coordinator, /setsid \/bin\/bash \/run\/home-lab-debian-production\.runner/);
assert.ok(coordinator.includes("/var/lib/home-lab/production-image-override.json"));
assert.ok(coordinator.includes("[.images[] | {service,image_id}] == [$expected[0].images[] | {service,image_id}]"));
assert.match(coordinator, /home-lab-\(arch\|debian\)-\(canary\|production\)\(-\[a-z-\]\+\)\?\\\.result/);
assert.match(coordinator, /mark_failed_production_evidence_awaiting_reboot/);
assert.ok(runner.includes("readonly CONFIRMATION=cutover-reviewed-vm-100-debian-production"));
assert.ok(finalizer.includes("readonly CONFIRMATION=finalize-reviewed-vm-100-debian-production-after-reboot"));
assert.match(production, /home-lab-production-guard\.service/);
assert.match(production, /Requires=home-lab-production-guard\.service/);
assert.match(production, /phase == \"committed\"/);
assert.match(coordinator, /capture_failed_production_activation/);
assert.match(coordinator, /crash-reconciliation/);
assert.match(coordinator, /compose-image-lock\.py capture/);
assert.match(revoker, /api_request\("DELETE", DEVICE_URL/);
assert.match(revoker, /api_request\("GET", DEVICES_URL, access_token\)/);
assert.match(revoker, /TAILSCALE_OAUTH_CLIENT_SECRET/);
for (const wrapper of [runner, finalizer]) {
  assert.match(wrapper, /\[\[ -t 0 \]\]/);
  assert.match(wrapper, /exec "\$root\/scripts\/qualify-debian-inert"/);
}

process.stdout.write("debian production cutover tests passed\n");
