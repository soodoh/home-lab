#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { load } = require("js-yaml");

const root = path.resolve(__dirname, "../..");
const contract = load(fs.readFileSync(path.join(root, "infrastructure/contract/home-lab.yml"), "utf8"));
const script = fs.readFileSync(path.join(root, "scripts/qualify-debian-inert"), "utf8");
const runner = fs.readFileSync(path.join(root, "scripts/run-debian-inert-qualification"), "utf8");
const restoreRunner = fs.readFileSync(path.join(root, "scripts/run-debian-inert-arch-restore"), "utf8");
const prepareRunner = fs.readFileSync(path.join(root, "scripts/run-debian-package-preparation"), "utf8");
const finalizeRunner = fs.readFileSync(path.join(root, "scripts/finalize-debian-package-preparation"), "utf8");
const transitionLibrary = fs.readFileSync(path.join(root, "scripts/lib/vm-100-os-transition"), "utf8");
const combined = `${script}\n${transitionLibrary}`;
const debian = contract.debian;

assert.ok(script.includes(`readonly IMAGE_URL=${debian.image.url}`));
assert.ok(script.includes(`readonly IMAGE_DIGEST_URL=${debian.image.digest_url}`));
assert.ok(script.includes(`readonly IMAGE_SHA512=${debian.image.sha512}`));
assert.match(script, /grep -Fxq "\$IMAGE_SHA512  \$IMAGE_FILENAME"/);
assert.ok(script.includes(`readonly IMAGE_PATH=${debian.image.staged_path}`));
assert.ok(script.includes(`readonly DEBIAN_CICUSTOM='${debian.cloud_init.cicustom}'`));
assert.ok(script.includes(`readonly DEBIAN_SCSI3='local-lvm:${debian.os_disk.path_in_datastore}`));
assert.ok(script.includes(`serial=${debian.os_disk.serial}`));
for (const [name, value] of [
  ["USER", debian.cloud_init.user_data],
  ["NETWORK", debian.cloud_init.network_data],
  ["META", debian.cloud_init.meta_data],
]) {
  assert.ok(script.includes(`readonly ${name}_SOURCE=${value.source_path}`));
  assert.ok(script.includes(`readonly ${name}_TARGET=${value.snippet_path}`));
  assert.ok(script.includes(`readonly ${name}_SHA256=${value.sha256}`));
  assert.ok(script.includes(`readonly ${name}_SIZE=${value.size}`));
}

assert.match(script, /ps -o tty= -p "\$\$"/);
assert.match(script, /source scripts\/lib\/vm-100-os-transition/);
assert.doesNotMatch(script, /validate-contract|\bnode\b/);
assert.match(script, /acquire_transition_locks/);
assert.match(combined, /release_transition_locks/);
assert.match(combined, /exec 8>&-/);
assert.match(combined, /exec 9>&-/);
assert.match(combined, /exec_without_transition_lock_fds qm start "\$VMID"/);
assert.match(combined, /exec_without_transition_lock_fds \/usr\/local\/sbin\/home-lab-vfio-recover/);
assert.match(script, /git rev-parse HEAD.*git rev-parse origin\/main/);
assert.match(script, /verify_plan_attestation/);
assert.match(script, /refs\/heads\/main:refs\/remotes\/origin\/main/);
assert.match(script, /refs\/notes\/debian-qualification/);
assert.match(script, /allActionsZero == true/);
assert.match(script, /\$age -ge -300 && \$age -le 86400/);
const shutdownIndex = script.indexOf("stage=shutdown-arch");
const imageInvocationIndex = script.indexOf('stage="stage-debian-image"');
const snippetInvocationIndex = script.indexOf('stage_snippet "$USER_SOURCE"');
assert.ok(imageInvocationIndex > 0 && imageInvocationIndex < shutdownIndex);
assert.ok(snippetInvocationIndex > 0 && snippetInvocationIndex < shutdownIndex);
const transitionStartedIndex = script.indexOf("transition_started=true", shutdownIndex);
const shutdownCommandIndex = script.indexOf('qm guest cmd "$VMID" shutdown', shutdownIndex);
assert.ok(shutdownIndex < transitionStartedIndex && transitionStartedIndex < shutdownCommandIndex);
assert.match(script, /PREVIOUS_USER_SHA256=.*\nreadonly PREVIOUS_USER_SIZE=4401/);
assert.match(script, /metadata == root:root:600:\$previous_size && \$actual == "\$previous_sha"/);
assert.match(script, /mv -T "\$pending" "\$target"/);
assert.match(script, /qm config "\$VMID" --current 1/);
assert.match(script, /stopped VM attachment differs/);
assert.match(script, /\[\[ \$volume_device != "\$state_volume_device" \]\]/);
assert.match(script, /\[\[ \$volume_device != "\$arch_volume_device" \]\]/);
assert.match(script, /blkdiscard --force "\$volume_device"/);
assert.ok(script.indexOf('qm set "$VMID" --scsi3 "$DEBIAN_SCSI3"') < script.indexOf('blkdiscard --force "$volume_device"'));
assert.match(script, /qemu-img convert .*"\$IMAGE_PATH" "\$volume_device"/);
assert.match(script, /qemu-img compare .*"\$IMAGE_PATH" "\$volume_device"/);
assert.doesNotMatch(script, /blkdiscard .*state_volume_(?:path|device)|qemu-img (?:convert|compare).*state_volume_(?:path|device)/);
assert.doesNotMatch(script, /qm (?:disk )?(?:unlink|detach|remove|destroy)|pvesm free|lvremove|wipefs|mkfs/);
assert.match(script, /qm cloudinit update "\$VMID"/);
assert.match(script, /'\/USER_DATA\.;1'/);
assert.match(script, /'\/NETWORK_CONFIG\.;1'/);
assert.match(script, /'\/META_DATA\.;1'/);
assert.match(script, /verify_arch_post_restore/);
assert.match(combined, /verify-arch-workloads/);
assert.match(script, /wait_for_agent 900/);
assert.match(script, /cloud-init status --wait/);
const cloudInitIndex = script.indexOf("stage=wait-cloud-init");
const provisionedShutdownIndex = script.indexOf("stage=shutdown-debian-after-provision");
const provisionedRestartIndex = script.indexOf("stage=start-debian-after-provision");
const gpuIndex = script.indexOf("stage=verify-debian-gpu");
assert.ok(cloudInitIndex < provisionedShutdownIndex && provisionedShutdownIndex < provisionedRestartIndex && provisionedRestartIndex < gpuIndex);
assert.match(script, /stage=shutdown-debian-after-provision[\s\S]*stop_console_capture[\s\S]*qm guest cmd "\$VMID" shutdown/);
assert.match(script, /stage=start-debian-after-provision[\s\S]*start_without_lock_inheritance[\s\S]*wait_for_agent 900/);
assert.ok(script.includes(`for module in ${debian.qualification.kernel_modules.join(" ")}`));
assert.match(script, /modinfo "\$module"/);
assert.ok(script.includes(`readonly KERNEL_RELEASE=${debian.qualification.kernel_release}`));
assert.ok(script.includes(debian.qualification.gpu_render_node));
assert.ok(script.includes(debian.qualification.gpu_vendor_device));
assert.match(script, /lspci -Dnns 02:00\.0.*\$GPU_VENDOR_DEVICE/);
assert.match(script, /lspci -Dnns 03:00\.0.*1002:ab30/);
for (const mount of debian.qualification.protected_mounts) {
  assert.ok(script.includes(mount));
}
assert.ok(script.includes("/etc/home-lab/allow-storage-activation"));
assert.match(script, /! command -v docker/);
assert.match(script, /prepare_arch_restore/);
assert.match(combined, /restore_stage=prepare-arch-restore/);
assert.match(script, /qm set "\$VMID" --cicustom "\$CURRENT_CICUSTOM"/);
assert.match(script, /CURRENT_IGNITION_SHA256=d60808452116247828f749517a66ec29d4656c4978d2997ab22e938d8cb4bc6d/);
assert.match(script, /restore_arch \|\| echo "critical: Arch restoration remains incomplete/);
assert.match(combined, /\[\[ \$\(os_id\) == arch \]\]/);
assert.match(combined, /qm set "\$VMID" --boot "\$ARCH_BOOT" --vga none/);
assert.match(combined, /qm guest cmd "\$VMID" shutdown.*qm shutdown "\$VMID" --timeout 60/);
assert.match(combined, /wait_for_status stopped 180/);
assert.ok(runner.includes("readonly CONFIRMATION=qualify-reviewed-vm-100-debian-13-inert"));
assert.match(runner, /\[\[ -t 0 \]\]/);
assert.match(runner, /exec "\$root\/scripts\/qualify-debian-inert"/);
assert.ok(restoreRunner.includes("readonly CONFIRMATION=restore-reviewed-vm-100-arch-after-debian-inert"));
assert.match(restoreRunner, /\[\[ -t 0 \]\]/);
assert.match(restoreRunner, /exec "\$root\/scripts\/qualify-debian-inert"/);
assert.match(script, /"\$RESTORE_CONFIRMATION"\) restore_mode=true/);
assert.match(script, /\[\[ \$\(os_id\) == debian \]\]/);
assert.match(script, /\[\[ \$\(config_value "\$config" boot\) == "\$DEBIAN_BOOT" \]\]/);
assert.match(script, /\[\[ \$\(config_value "\$config" scsi3\) == "\$DEBIAN_SCSI3" \]\]/);
assert.match(script, /\[\[ \$\(config_value "\$config" cicustom\) == "\$DEBIAN_CICUSTOM" \]\]/);
assert.ok(prepareRunner.includes("readonly CONFIRMATION=prepare-reviewed-vm-100-debian-packages"));
assert.match(prepareRunner, /\[\[ -t 0 \]\]/);
assert.match(prepareRunner, /exec "\$root\/scripts\/qualify-debian-inert"/);
assert.match(script, /"\$PREPARE_CONFIRMATION"\) prepare_mode=true/);
assert.match(script, /package preparation requires the exact qualified Debian disk/);
assert.match(script, /prepare_source=infrastructure\/debian\/prepare-packages\.sh/);
assert.match(script, /prepare_sha=24fdefb745e6b6bb6ef2f286070fe70f64482401104700d888ac7e8e4623b7cd/);
assert.match(script, /guest_exec_ok 1800 \/bin\/bash -lc/);
assert.match(script, /\/bin\/bash \\"\\\$target\\" > \/var\/log\/home-lab-debian-package-preparation\.log/);
assert.match(script, /guest-exec-failure\.json/);
assert.match(script, /jq -r '\(\."out-data" \/\/ ""\) \+ \(\."err-data" \/\/ ""\)'/);
assert.match(script, /cat \/var\/log\/home-lab-debian-package-preparation\.log/);
assert.match(script, /home-lab-debian-packages-prepared-v1/);
const packageIndex = script.indexOf("stage=prepare-debian-packages");
const pendingIndex = script.indexOf('write_package_pending_evidence "$prepare_marker"');
const prepareRebootIndex = script.indexOf("  prepare_arch_host_reboot_path", pendingIndex);
const awaitingIndex = script.indexOf('mark_package_evidence_awaiting_reboot "', prepareRebootIndex);
assert.ok(packageIndex < pendingIndex && pendingIndex < prepareRebootIndex && prepareRebootIndex < awaitingIndex);
assert.match(script, /if guest_exec_ok 30 \/usr\/bin\/test -f \/var\/lib\/home-lab\/debian-packages-prepared\.json; then[\s\S]*stage=verify-existing-debian-packages[\s\S]*else[\s\S]*stage=prepare-debian-packages/);
assert.match(script, /prepare_mode == true && \$transition_started == true[\s\S]*prepare_arch_host_reboot_path/);
assert.match(script, /timeout 15 qm guest cmd "\$VMID" shutdown/);
assert.match(script, /state:"package-verified"/);
assert.match(script, /state:"awaiting-host-reboot"/);
const cleanupBody = script.match(/cleanup\(\) \{[\s\S]*?\n\}/)[0];
assert.doesNotMatch(cleanupBody, /PREPARE_PENDING_LOG|PREPARE_LOG/);
assert.match(script, /hostBootIdBefore/);
assert.match(script, /host_boot_id_after != .*hostBootIdBefore/);
assert.match(script, /verify_exact_arch_configuration/);
assert.match(script, /arch_config_sha256/);
assert.match(script, /verify_arch_post_restore[\s\S]*pve-firewall status[\s\S]*mv -T "\$finalize_evidence" "\$PREPARE_LOG"/);
assert.match(script, /"\$FINALIZE_CONFIRMATION"\) finalize_mode=true/);
assert.ok(finalizeRunner.includes("readonly CONFIRMATION=finalize-reviewed-vm-100-debian-packages-after-reboot"));
assert.match(finalizeRunner, /\[\[ -t 0 \]\]/);
assert.match(finalizeRunner, /exec "\$root\/scripts\/qualify-debian-inert"/);
assert.match(script, /guest_exec_ok 60 .*docker ps.*\|\| return 1/);
assert.match(script, /candidate_diagnostics \|\| echo "warning: candidate diagnostics could not be persisted/);
for (const signal of ["INT", "TERM", "HUP"]) assert.match(script, new RegExp(`trap .* ${signal}`));
assert.match(script, /trap - ERR INT TERM HUP/);
process.stdout.write("debian inert qualification tests passed\n");
